// アクセス元のホスト名に応じて自動でAPIのURLを決定する
// 手動で書き換える必要はありません

const _host = window.location.hostname;
const API_BASE = (_host === 'localhost' || _host === '127.0.0.1')
  ? 'http://localhost:8080'          // PCのブラウザからのアクセス
  : `http://${_host}:8080`;          // スマホ・別PC・サーバーからのアクセス

