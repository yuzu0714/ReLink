/* =====================================================
   環境設定ファイル
   ★修正：USE_LAN の手動切り替えを廃止。
   ブラウザで開いているURLのホスト名から、API_BASE を自動で決めるようにした。
   ===================================================== */

// ★追加：ホスト名が取れない場合(file://で直接開いた時など)だけ使う予備のIP
// 通常のアクセス(http://〜)では使われない
const LAN_IP = '172.20.74.114';

// ★追加：今開いているページのホスト名を取得する
// 例) PCで localhost:5500 を開いた → "localhost"
//     スマホで 192.168.3.85:5500 を開いた → "192.168.3.85"
const _pageHost = window.location.hostname;

// ★追加：開いたURLと同じホストの8080番をAPIとして使う
// これでスマホからアクセスしても、PCからアクセスしても、
// 手動でconfig.jsを書き換えなくても正しいAPIにつながる
const API_BASE = `http://${_pageHost || LAN_IP}:8080`;

// 本番サーバーへ接続する場合は、上の API_BASE を以下に差し替える
// const API_BASE = 'http://157.17.49.232:8080';